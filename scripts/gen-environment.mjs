// gen-environment.mjs — generate src/environments/environment.ts from .env.local / process.env.
//
// Ported pattern from SGC: environment.ts is GENERATED and GITIGNORED. The only build-time inputs the
// public site needs are SUPABASE_URL, SUPABASE_ANON_KEY, SITE_URL and ENV_NAME. Secrets never live in src/.
//
// Usage:
//   node scripts/gen-environment.mjs --env dev
//   node scripts/gen-environment.mjs --env prod
//
// Env resolution precedence per key, for a given <ENV> (DEV|PROD):
//   process.env[KEY_<ENV>]  ->  process.env[KEY]  ->  .env.local[KEY_<ENV>]  ->  .env.local[KEY]  ->  ''
// This lets Vercel inject plain KEYs per-environment while local dev uses the *_DEV / *_PROD suffixes
// in .env.local (the same file the Supabase scripts read).

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT_DIR = join(ROOT, 'src', 'environments');
const OUT_FILE = join(OUT_DIR, 'environment.ts');

// --- parse a minimal .env file (KEY=VALUE, ignores blanks/#comments, strips surrounding quotes) ---
function parseEnvFile(path) {
  const out = {};
  if (!existsSync(path)) return out;
  for (const raw of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

export function resolveEnvName(explicit) {
  if (explicit) return explicit;
  // On Vercel: main -> prod, every other branch -> dev (preview).
  const ref = process.env.VERCEL_GIT_COMMIT_REF;
  if (ref) return ref === 'main' ? 'prod' : 'dev';
  return process.env.ENV_NAME === 'prod' ? 'prod' : 'dev';
}

export function generateEnvironment(envName) {
  const SUFFIX = envName.toUpperCase(); // DEV | PROD
  const fileVars = parseEnvFile(join(ROOT, '.env.local'));

  const pick = (key, fallback = '') => {
    const candidates = [
      process.env[`${key}_${SUFFIX}`],
      process.env[key],
      fileVars[`${key}_${SUFFIX}`],
      fileVars[key],
    ];
    for (const c of candidates) {
      if (c !== undefined && c !== '') return c;
    }
    return fallback;
  };

  const siteUrlFallback =
    envName === 'prod' ? 'https://constructorasd.com' : 'http://localhost:4200';

  const environment = {
    envName,
    production: envName === 'prod',
    supabaseUrl: pick('SUPABASE_URL'),
    supabaseAnonKey: pick('SUPABASE_ANON_KEY'),
    siteUrl: pick('SITE_URL', siteUrlFallback),
  };

  const banner =
    '// AUTO-GENERATED by scripts/gen-environment.mjs — DO NOT EDIT, DO NOT COMMIT (gitignored).\n' +
    `// Generated for ENV_NAME="${envName}".\n`;
  // No `as const`: envName/production stay widened (string/boolean) so env comparisons type-check.
  const body = `export const environment = ${JSON.stringify(environment, null, 2)};\n`;

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, banner + body, 'utf8');
  return environment;
}

// --- CLI ---
const isMain = fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--env');
  const explicit = i !== -1 ? argv[i + 1] : undefined;
  if (explicit && !['dev', 'prod'].includes(explicit)) {
    console.error(`✖ gen-environment: --env must be "dev" or "prod" (got "${explicit}")`);
    process.exit(1);
  }
  const envName = resolveEnvName(explicit);
  const env = generateEnvironment(envName);
  console.log(
    `✔ environment.ts generated → envName=${env.envName} siteUrl=${env.siteUrl} ` +
      `supabaseUrl=${env.supabaseUrl ? '(set)' : '(empty)'}`,
  );
}
